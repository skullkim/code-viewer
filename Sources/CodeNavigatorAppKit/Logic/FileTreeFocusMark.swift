import Foundation

/// 트리 행에 포커스 링을 그릴지 (REQ-003, D-8).
///
/// **링은 "화살표가 여기 있다"는 약속이다.** 그 약속을 지키려면 트리가 실제로 키보드를
/// 갖고 있을 때만 그려야 한다.
///
/// D-8 은 그 약속이 깨진 것이었다: 행을 클릭하면 링이 떴지만 키보드는 에디터에 있어서,
/// ↓ 를 누르면 **트리 선택이 아니라 nvim 커서가 움직였다**(QA 실측 1,1 → 3,1). 사용자는
/// 트리를 움직이려다 **편집 위치를 잃는다** — 아무 일도 안 일어나는 것보다 나쁘다.
///
/// 그래서 링만 지우는 것은 답이 아니다. 그러면 "트리에 키보드로 갈 수 없다"는 사실이
/// 감춰질 뿐이다. **링이 진실이 되게 하거나, 클릭이 진짜로 포커스를 옮기거나** 둘 중
/// 하나여야 하고, 여기서는 둘 다 했다.
public enum FileTreeFocusMark {

    /// 선택된 행이면서 **트리가 키보드를 가진** 경우에만 링.
    public static func showsKeyboardCursor(isSelected: Bool, treeOwnsKeyboard: Bool) -> Bool {
        isSelected && treeOwnsKeyboard
    }
}
